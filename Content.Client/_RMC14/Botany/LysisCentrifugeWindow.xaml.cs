using Content.Client.UserInterface.Controls;
using Content.Shared._RMC14.Botany;
using Robust.Client.AutoGenerated;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.GameObjects;
using Robust.Shared.IoC;
using Robust.Shared.Maths;

namespace Content.Client._RMC14.Botany;

[GenerateTypedNameReferences]
public sealed partial class LysisCentrifugeWindow : FancyWindow
{
    private const string EjectIcon = "/Textures/_RMC14/Interface/Icons/dark/eject.svg.192dpi.png";
    private const string EjectIconWhite = "/Textures/_RMC14/Interface/Icons/white/eject.svg.192dpi.png";
    private const string ProcessIcon = "/Textures/_RMC14/Interface/Icons/dark/arrows-rotate.svg.192dpi.png";
    private const string ProcessIconWhite = "/Textures/_RMC14/Interface/Icons/white/arrows-rotate.svg.192dpi.png";
    private const string TrashIcon = "/Textures/_RMC14/Interface/Icons/dark/trash.svg.192dpi.png";
    private const string TrashIconWhite = "/Textures/_RMC14/Interface/Icons/white/trash.svg.192dpi.png";
    private const string ExtractIcon = "/Textures/_RMC14/Interface/Icons/dark/square-plus.svg.192dpi.png";
    private const string ExtractIconWhite = "/Textures/_RMC14/Interface/Icons/white/square-plus.svg.192dpi.png";

    private readonly IResourceCache _resourceCache;

    private LysisCentrifugeBui? _bui;

    public LysisCentrifugeWindow()
    {
        RobustXamlLoader.Load(this);

        _resourceCache = IoCManager.Resolve<IResourceCache>();

        BotanyUiStyle.Header(GenomeHeader);
        BotanyUiStyle.Header(DiscHeader);
        BotanyUiStyle.Header(GenesHeader);

        BotanyUiStyle.IconButton(_resourceCache, EjectSeedButton, EjectIcon, EjectIconWhite, "Eject Seed");
        BotanyUiStyle.IconButton(_resourceCache, ProcessSeedButton, ProcessIcon, ProcessIconWhite, "Process Genome");
        BotanyUiStyle.IconButton(_resourceCache, ClearBufferButton, TrashIcon, TrashIconWhite, "Clear Buffer");
        BotanyUiStyle.IconButton(_resourceCache, EjectDiscButton, EjectIcon, EjectIconWhite, "Eject Disc");

        ProcessSeedButton.OnPressed += _ => _bui?.ProcessSeed();
        EjectSeedButton.OnPressed += _ => _bui?.EjectSeed();
        ClearBufferButton.OnPressed += _ => _bui?.ClearBuffer();
        EjectDiscButton.OnPressed += _ => _bui?.EjectDisc();
    }

    public void SetBui(LysisCentrifugeBui bui)
    {
        _bui = bui;
    }

    public void UpdateState(LysisCentrifugeComponent comp)
    {
        SeedSpriteView.Visible = comp.HasSeed && comp.SeedEntityNet.HasValue;
        if (comp.SeedEntityNet.HasValue)
            SeedSpriteView.SetEntity(comp.SeedEntityNet.Value);
        else
            SeedSpriteView.SetEntity((EntityUid?) null);

        SeedTraitsGrid.DisposeAllChildren();

        if (comp.HasSeed)
        {
            var seedText = comp.SeedPacketName is { } packetName
                ? BotanyUiStyle.ShortSeedName(packetName)
                : "[Seed inserted]";
            BotanyUiStyle.StatusRow(SeedStatusPanel, SeedStatusLabel, seedText, BotanyUiStyle.GreenColor);
            SeedStatusLabel.ToolTip = comp.SeedPacketName;

            BotanyUiStyle.AddStatRow(SeedTraitsGrid, "Endurance", $"{comp.SeedEndurance:0.#}");
            BotanyUiStyle.AddStatRow(SeedTraitsGrid, "Yield", $"{comp.SeedYield}");
            BotanyUiStyle.AddStatRow(SeedTraitsGrid, "Potency", $"{comp.SeedPotency:0.#}");
            BotanyUiStyle.AddStatRow(SeedTraitsGrid, "Lifespan", $"{comp.SeedLifespan:0.#}");
            BotanyUiStyle.AddStatRow(SeedTraitsGrid, "Maturation", $"{comp.SeedMaturation:0.#}");
            BotanyUiStyle.AddStatRow(SeedTraitsGrid, "Production", $"{comp.SeedProduction:0.#}");
            BotanyUiStyle.AddStatRow(SeedTraitsGrid, "Harvest", BotanyUiStyle.GetHarvestLabel(comp.SeedHarvestRepeat));
            BotanyUiStyle.AddStatRow(SeedTraitsGrid, "Seedless", comp.SeedSeedless ? "Yes" : "No");
            BotanyUiStyle.AddStatRow(SeedTraitsGrid, "Viable", comp.SeedViable ? "Yes" : "No");
        }
        else
        {
            BotanyUiStyle.StatusRow(SeedStatusPanel, SeedStatusLabel, "[No seed loaded]", BotanyUiStyle.RedColor);
            SeedStatusLabel.ToolTip = null;
        }

        var hasGenome = comp.GenomeName != null;

        if (hasGenome)
        {
            var ratio = comp.MaxDegradation > 0
                ? comp.Degradation / (float) comp.MaxDegradation
                : 0f;
            var color = ratio >= 0.75f ? BotanyUiStyle.RedColor : ratio >= 0.4f ? BotanyUiStyle.TanColor : BotanyUiStyle.GreenColor;

            BotanyUiStyle.StatusRow(GenomeStatusPanel, GenomeNameLabel, comp.GenomeName!, color);
            DegradationMetric.SetAccentColor(color);
            DegradationMetric.Update("Degradation", $"{comp.Degradation}/{comp.MaxDegradation}", progress: ratio);
        }
        else
        {
            BotanyUiStyle.StatusRow(GenomeStatusPanel, GenomeNameLabel, "[No genome loaded]", BotanyUiStyle.RedColor);
            DegradationMetric.SetAccentColor(BotanyUiStyle.GreenColor);
            DegradationMetric.Update("Degradation", "—", progress: 0f);
        }

        if (comp.HasDisc)
            BotanyUiStyle.StatusRow(DiscStatusPanel, DiscStatusLabel, "[Disc inserted]", BotanyUiStyle.GreenColor);
        else
            BotanyUiStyle.StatusRow(DiscStatusPanel, DiscStatusLabel, "[No disc]", BotanyUiStyle.RedColor);

        GenesSection.Visible = hasGenome;

        GeneButtonsContainer.DisposeAllChildren();

        if (!hasGenome)
            return;

        foreach (var slot in comp.GeneSlots)
        {
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                Margin = new Thickness(0, 1),
            };

            var typeName = slot.GeneType.GetLabel();
            var typeDesc = slot.GeneType.GetDescription();
            var labelText = slot.AlreadyOnDisc
                ? $"{slot.ObfuscatedCode} - {typeName}: ✓"
                : $"{slot.ObfuscatedCode} - {typeName}:";

            var label = new Label
            {
                Text = labelText,
                ToolTip = typeDesc,
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
            };

            var geneType = slot.GeneType;
            string? btnTooltip = null;
            if (slot.AlreadyOnDisc)
                btnTooltip = "This gene sequence is already on the disc.";
            else if (comp.DiscFull)
                btnTooltip = "Disc already contains a gene sequence.";

            var btn = new Button { ToolTip = btnTooltip };
            BotanyUiStyle.IconButton(_resourceCache, btn, ExtractIcon, ExtractIconWhite, "Extract gene");
            btn.OnPressed += _ => _bui?.ExtractGene(geneType);

            row.AddChild(label);
            row.AddChild(btn);
            GeneButtonsContainer.AddChild(row);
        }
    }
}
