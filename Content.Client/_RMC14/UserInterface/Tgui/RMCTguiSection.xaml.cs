using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.UserInterface.Tgui;

[GenerateTypedNameReferences]
public sealed partial class RMCTguiSection : PanelContainer
{
    [Dependency] private readonly IResourceCache _resourceCache = default!;

    public RMCTguiSection()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        PanelOverride = new StyleBoxFlat(RMCTguiStyle.SectionBackground);
        TitleRule.PanelOverride = new StyleBoxFlat(RMCTguiStyle.Primary);
        TitleLabel.FontOverride = RMCTguiStyle.BoldFont(_resourceCache, RMCTguiStyle.TitleFontSize);
        TitleLabel.FontColorOverride = RMCTguiStyle.Foreground;
        XamlChildren = ContentContainer.Children;
    }

    public string? Title
    {
        get => TitleLabel.Text;
        set
        {
            TitleLabel.Text = value;
            TitleContainer.Visible = !string.IsNullOrEmpty(value);
        }
    }
}
