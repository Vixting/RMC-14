using Robust.Client.AutoGenerated;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.UserInterface.Tgui;

[GenerateTypedNameReferences]
public sealed partial class RMCTguiGroup : BoxContainer
{
    [Dependency] private readonly IResourceCache _resourceCache = default!;

    public RMCTguiGroup()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        TitleLabel.FontOverride = RMCTguiStyle.BoldFont(_resourceCache, RMCTguiStyle.SmallFontSize);
        TitleLabel.FontColorOverride = RMCTguiStyle.GroupTitle;
        XamlChildren = ContentContainer.Children;
    }

    public string? Title
    {
        get => TitleLabel.Text;
        set => TitleLabel.Text = value?.ToUpperInvariant();
    }

    public void UpdateVisibility()
    {
        foreach (var child in ContentContainer.Children)
        {
            if (!child.Visible)
                continue;

            Visible = true;
            return;
        }

        Visible = false;
    }
}
