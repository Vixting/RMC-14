using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.UserInterface.Tgui;

[GenerateTypedNameReferences]
public sealed partial class RMCTguiShadowLabel : Control
{
    public RMCTguiShadowLabel()
    {
        RobustXamlLoader.Load(this);
        ShadowLabel.FontColorOverride = RMCTguiStyle.TextShadow;
    }

    public string? Text
    {
        get => TextLabel.Text;
        set
        {
            TextLabel.Text = value;
            ShadowLabel.Text = value;
        }
    }

    public Font? FontOverride
    {
        get => TextLabel.FontOverride;
        set
        {
            TextLabel.FontOverride = value;
            ShadowLabel.FontOverride = value;
        }
    }

    public Color? FontColorOverride
    {
        get => TextLabel.FontColorOverride;
        set => TextLabel.FontColorOverride = value;
    }

    public bool ClipText
    {
        get => TextLabel.ClipText;
        set
        {
            TextLabel.ClipText = value;
            ShadowLabel.ClipText = value;
        }
    }
}
