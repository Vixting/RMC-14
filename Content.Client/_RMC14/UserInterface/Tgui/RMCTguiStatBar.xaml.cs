using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.UserInterface.Tgui;

[GenerateTypedNameReferences]
public sealed partial class RMCTguiStatBar : PanelContainer
{
    [Dependency] private readonly IResourceCache _resourceCache = default!;

    private readonly StyleBoxFlat _border = new()
    {
        BackgroundColor = Color.Transparent,
        BorderThickness = new Thickness(1),
    };

    public RMCTguiStatBar()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        PanelOverride = _border;
        NameLabel.FontOverride = RMCTguiStyle.RegularFont(_resourceCache);
        NameLabel.FontColorOverride = RMCTguiStyle.Foreground;
        BaseValueLabel.FontOverride = RMCTguiStyle.RegularFont(_resourceCache);
        BaseValueLabel.FontColorOverride = RMCTguiStyle.BaseValueText;
        ValueLabel.FontOverride = RMCTguiStyle.BoldFont(_resourceCache);
        ValueLabel.FontColorOverride = RMCTguiStyle.Foreground;
    }

    public void SetStat(
        string name,
        RMCTguiStatText text,
        float value,
        float max,
        RMCTguiStatRating rating,
        float? baseValue = null,
        string? tooltip = null)
    {
        var ratio = max > 0 ? value / max : 0;
        var color = GetColor(ratio, rating);

        Visible = true;
        ToolTip = tooltip;
        NameLabel.Text = name;
        ValueLabel.Text = text.Value;

        BaseValueLabel.Visible = text.Base != null;
        if (text.Base != null)
            BaseValueLabel.Text = $"{text.Base} →";

        ValueLabel.FontColorOverride = text.Base != null && baseValue != null
            ? GetChangeColor(value, baseValue.Value, rating)
            : RMCTguiStyle.Foreground;

        Fill.Ratio = ratio;
        Fill.BaseRatio = baseValue != null && max > 0 && !MathHelper.CloseTo(baseValue.Value, value)
            ? baseValue.Value / max
            : null;
        Fill.FillColor = color;
        _border.BorderColor = color;
    }

    private static Color GetChangeColor(float value, float baseValue, RMCTguiStatRating rating)
    {
        var better = rating switch
        {
            RMCTguiStatRating.HigherIsBetter => value > baseValue,
            RMCTguiStatRating.LowerIsBetter => value < baseValue,
            _ => (bool?) null,
        };

        if (better == null || MathHelper.CloseTo(value, baseValue))
            return RMCTguiStyle.Foreground;

        return RMCTguiStyle.Light(better.Value ? RMCTguiStyle.Good : RMCTguiStyle.Bad);
    }

    private static Color GetColor(float ratio, RMCTguiStatRating rating)
    {
        return rating switch
        {
            RMCTguiStatRating.LowerIsBetter => ratio < 0.25f
                ? RMCTguiStyle.Good
                : ratio < 0.5f ? RMCTguiStyle.Average : RMCTguiStyle.Bad,
            RMCTguiStatRating.HigherIsBetter => ratio < 0.25f
                ? RMCTguiStyle.Bad
                : ratio < 0.5f ? RMCTguiStyle.Average : RMCTguiStyle.Good,
            _ => RMCTguiStyle.Neutral,
        };
    }
}

public readonly record struct RMCTguiStatText(string Value, string? Base = null)
{
    public static implicit operator RMCTguiStatText(string value)
    {
        return new RMCTguiStatText(value);
    }
}

public enum RMCTguiStatRating
{
    Neutral,
    LowerIsBetter,
    HigherIsBetter,
}
