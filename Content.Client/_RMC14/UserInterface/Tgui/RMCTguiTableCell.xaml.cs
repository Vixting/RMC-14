using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.UserInterface.Tgui;

[GenerateTypedNameReferences]
public sealed partial class RMCTguiTableCell : PanelContainer
{
    [Dependency] private readonly IResourceCache _resourceCache = default!;

    private readonly StyleBoxFlat _box = RMCTguiStyle.Box(Color.Transparent, vertical: 1);

    public RMCTguiTableCell()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        PanelOverride = _box;
        CellLabel.FontOverride = RMCTguiStyle.RegularFont(_resourceCache);
        CellLabel.FontColorOverride = RMCTguiStyle.Foreground;
    }

    public RMCTguiTableCell(string text, bool bold = false, Color? color = null, Color? background = null, string? tooltip = null) : this()
    {
        CellLabel.Text = text;
        CellLabel.FontOverride = bold ? RMCTguiStyle.BoldFont(_resourceCache) : RMCTguiStyle.RegularFont(_resourceCache);
        CellLabel.FontColorOverride = color ?? RMCTguiStyle.Foreground;
        _box.BackgroundColor = background ?? Color.Transparent;
        ToolTip = tooltip;
        MouseFilter = tooltip == null ? MouseFilterMode.Ignore : MouseFilterMode.Pass;
    }

    public bool RowHeader
    {
        get => !HorizontalExpand;
        set
        {
            HorizontalExpand = !value;
            CellLabel.Align = value ? Label.AlignMode.Left : Label.AlignMode.Center;
        }
    }
}
