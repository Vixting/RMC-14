using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.UserInterface.Tgui;

[GenerateTypedNameReferences]
[Virtual]
public partial class RMCTguiWindow : BaseWindow
{
    [Dependency] private readonly IResourceCache _resourceCache = default!;

    private const float TitleBarHeight = 26;
    private const float ScreenMargin = 20;

    private readonly StyleBoxFlat _closeNormal = new(Color.Transparent);
    private readonly StyleBoxFlat _closeHover = new(RMCTguiStyle.CloseHoverBackground);

    public RMCTguiWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        XamlChildren = ContentsContainer.Children;

        WindowBackground.PanelOverride = new StyleBoxFlat(RMCTguiStyle.WindowBackground)
        {
            BorderColor = RMCTguiStyle.WindowBorder,
            BorderThickness = new Thickness(1),
        };

        TitleBar.PanelOverride = new StyleBoxFlat(RMCTguiStyle.TitleBarBackground)
        {
            BorderColor = RMCTguiStyle.WindowBorder,
            BorderThickness = new Thickness(0, 0, 0, 1),
        };

        TitleLabel.FontOverride = RMCTguiStyle.RegularFont(_resourceCache, RMCTguiStyle.TitleFontSize);
        TitleLabel.FontColorOverride = RMCTguiStyle.TitleText;

        CloseLabel.FontOverride = RMCTguiStyle.RegularFont(_resourceCache, RMCTguiStyle.CloseFontSize);
        CloseLabel.FontColorOverride = RMCTguiStyle.CloseText;
        CloseButton.StyleBoxOverride = _closeNormal;
        CloseButton.OnMouseEntered += _ => SetCloseHovered(true);
        CloseButton.OnMouseExited += _ => SetCloseHovered(false);
        CloseButton.OnPressed += _ => Close();
    }

    public string? Title
    {
        get => TitleLabel.Text;
        set => TitleLabel.Text = value;
    }

    private void SetCloseHovered(bool hovered)
    {
        CloseButton.StyleBoxOverride = hovered ? _closeHover : _closeNormal;
        CloseLabel.FontColorOverride = hovered ? RMCTguiStyle.Foreground : RMCTguiStyle.CloseText;
    }

    protected override void Opened()
    {
        base.Opened();

        if (Parent != null)
            MaxHeight = Math.Max(Parent.Size.Y - ScreenMargin * 2, TitleBarHeight * 4);
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        return relativeMousePos.Y < TitleBarHeight ? DragMode.Move : DragMode.None;
    }
}
