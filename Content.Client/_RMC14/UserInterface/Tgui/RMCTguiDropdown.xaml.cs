using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.UserInterface.Tgui;

[GenerateTypedNameReferences]
public sealed partial class RMCTguiDropdown : ContainerButton
{
    [Dependency] private readonly IResourceCache _resourceCache = default!;

    private const float MaxMenuHeight = 300;

    private readonly StyleBoxFlat _normal = RMCTguiStyle.Box(RMCTguiStyle.Neutral, 5);
    private readonly StyleBoxFlat _hover = RMCTguiStyle.Box(RMCTguiStyle.NeutralHover, 5);
    private readonly StyleBoxFlat _itemNormal = RMCTguiStyle.Box(Color.Transparent, 3, 2);
    private readonly StyleBoxFlat _itemHover = RMCTguiStyle.Box(RMCTguiStyle.MenuItemHover, 3, 2);
    private readonly StyleBoxFlat _itemSelected = RMCTguiStyle.Box(RMCTguiStyle.MenuItemSelected, 3, 2);

    private readonly Popup _popup = new();
    private readonly BoxContainer _menu = new() { Orientation = BoxContainer.LayoutOrientation.Vertical };
    private readonly ScrollContainer _scroll = new()
    {
        HScrollEnabled = false,
        ReturnMeasure = true,
        MaxHeight = MaxMenuHeight,
    };

    private readonly Font _font;
    private readonly List<Item> _items = new();

    public int SelectedId { get; private set; } = -1;

    public int ItemCount => _items.Count;

    public event Action<int>? OnItemSelected;

    public RMCTguiDropdown()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _font = RMCTguiStyle.RegularFont(_resourceCache);

        StyleBoxOverride = _normal;
        SelectedLabel.FontOverride = _font;
        SelectedLabel.FontColorOverride = RMCTguiStyle.Foreground;
        Arrow.Modulate = RMCTguiStyle.Foreground;

        _scroll.AddChild(_menu);
        _popup.AddChild(new PanelContainer
        {
            PanelOverride = new StyleBoxFlat(RMCTguiStyle.MenuBackground)
            {
                BorderColor = RMCTguiStyle.WindowBorder,
                BorderThickness = new Thickness(1),
            },
        });
        _popup.AddChild(_scroll);
        _popup.OnPopupHide += () => UserInterfaceManager.ModalRoot.RemoveChild(_popup);

        OnPressed += _ => OpenMenu();
    }

    public void AddItem(string text, int id)
    {
        var label = new Label
        {
            Text = text,
            FontOverride = _font,
            FontColorOverride = RMCTguiStyle.Foreground,
        };

        var button = new ContainerButton { StyleBoxOverride = _itemNormal };
        button.AddChild(label);

        var item = new Item(id, button, label);
        button.OnPressed += _ => Choose(item);
        button.OnMouseEntered += _ => SetItemStyle(item, true);
        button.OnMouseExited += _ => SetItemStyle(item, false);

        _items.Add(item);
        _menu.AddChild(button);

        if (_items.Count == 1)
            SelectId(id);
    }

    public void SelectId(int id)
    {
        foreach (var item in _items)
        {
            if (item.Id != id)
                continue;

            SelectedId = id;
            SelectedLabel.Text = item.Label.Text;
            return;
        }
    }

    public void SetItemText(int id, string text)
    {
        foreach (var item in _items)
        {
            if (item.Id != id)
                continue;

            item.Label.Text = text;
            if (SelectedId == id)
                SelectedLabel.Text = text;

            return;
        }
    }

    protected override void DrawModeChanged()
    {
        base.DrawModeChanged();
        StyleBoxOverride = DrawMode is DrawModeEnum.Hover or DrawModeEnum.Pressed ? _hover : _normal;
    }

    private void OpenMenu()
    {
        foreach (var item in _items)
        {
            SetItemStyle(item, false);
        }

        _scroll.Measure(Vector2Helpers.Infinity);
        var position = GlobalPosition + new Vector2(0, Size.Y + 1);
        var size = new Vector2(Math.Max(_scroll.DesiredSize.X, Width), _scroll.DesiredSize.Y);

        UserInterfaceManager.ModalRoot.AddChild(_popup);
        _popup.Open(UIBox2.FromDimensions(position, size));
    }

    private void Choose(Item item)
    {
        _popup.Close();
        SelectId(item.Id);
        OnItemSelected?.Invoke(item.Id);
    }

    private void SetItemStyle(Item item, bool hovered)
    {
        item.Button.StyleBoxOverride = item.Id == SelectedId
            ? _itemSelected
            : hovered ? _itemHover : _itemNormal;
    }

    private sealed record Item(int Id, ContainerButton Button, Label Label);
}
