using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.UserInterface.Tgui;

[GenerateTypedNameReferences]
public sealed partial class RMCTguiTag : PanelContainer
{
    [Dependency] private readonly IResourceCache _resourceCache = default!;

    private readonly StyleBoxFlat _box = new()
    {
        BorderThickness = new Thickness(1),
        ContentMarginLeftOverride = 5,
        ContentMarginRightOverride = 5,
        ContentMarginTopOverride = 1,
        ContentMarginBottomOverride = 1,
    };

    public RMCTguiTag()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        PanelOverride = _box;
        TagLabel.FontOverride = RMCTguiStyle.BoldFont(_resourceCache, RMCTguiStyle.SmallFontSize);
    }

    public void SetTag(string text, Color color, string? tooltip = null)
    {
        TagLabel.Text = text;
        TagLabel.FontColorOverride = RMCTguiStyle.Light(color);
        _box.BackgroundColor = color.WithAlpha(0.2f);
        _box.BorderColor = color;
        ToolTip = tooltip;
    }
}
